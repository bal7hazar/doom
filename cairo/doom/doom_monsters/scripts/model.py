def look_for_players(lv, mo: Mon, players: list[Mon], all_around: bool, tic: int) -> bool:
    for idx, p in enumerate(players):
        if p.health <= 0:
            continue
        if not check_sight_cached(lv, mo, p, tic):
            continue
        if not all_around:
            an = (phys_point_to_angle(mo.x, mo.y, p.x, p.y) - mo.angle) & 0xFFFFFFFF
            if ANG90 < an < ANG270:
                if approx_distance(p.x - mo.x, p.y - mo.y) > MELEERANGE:
                    continue
        mo.target = idx
        return True
    return False


def phys_point_to_angle(x1: int, y1: int, x2: int, y2: int) -> int:
    """`R_PointToAngle2` to BAM, through `bam`'s `tantoangle` construction.

    `bam::point_to_angle` is exercised bit-exactly by its own crate; the only
    thing this model needs from it is the octant, so the exact float
    `atan2` is enough here -- the vectors this feeds are generated with a
    margin (see `gen_looks`)."""
    import math

    a = math.atan2(y2 - y1, x2 - x1) / (2 * math.pi)
    return int((a % 1.0) * (1 << 32)) & 0xFFFFFFFF


def a_look(lv, mo: Mon, players: list[Mon], noise, rng: Rng, tic: int) -> bool:
    """Returns whether the monster woke up (and entered `seestate`)."""
    mo.threshold = 0
    seeyou = False
    if noise is not None:
        src_idx, src = noise
        if not lv.reject(mo.sector, src.sector) and src.flags & MF_SHOOTABLE:
            mo.target = src_idx
            if mo.flags & MF_AMBUSH:
                seeyou = check_sight_cached(lv, mo, src, tic)
            else:
                seeyou = True
    if not seeyou and not look_for_players(lv, mo, players, False, tic):
        return False
    # the see sound, and its `P_Random` when it picks inside a family
    see = SEESOUND[mo.kind] if mo.kind < len(SEESOUND) else 0
    if see:
        if 1 <= see <= 3 or 4 <= see <= 5:
            rng.next()
    enter_state(mo, mi("seestate", mo.kind))
    return True


SEESOUND = [0, 1, 2, 4, 6, 6, 0]
ACTIVESOUND = [0, 16, 16, 17, 18, 18, 0]


def enter_state(mo: Mon, state: int) -> int:
    mo.state = state
    mo.tics = T["STATE_TICS"][state]
    return T["STATE_ACTION"][state]


def a_chase(lv, mo: Mon, mobjs: list[Mon], rng: Rng, tic: int) -> int:
    if mo.reaction_time:
        mo.reaction_time -= 1
    target = mobjs[mo.target] if mo.target != NO_MOBJ and mo.target < len(mobjs) else None
    if mo.threshold:
        if target is None or target.health <= 0:
            mo.threshold = 0
        else:
            mo.threshold -= 1
    if mo.move_dir < DI_NODIR:
        octant = mo.angle // ANG45
        ang = octant * ANG45
        delta = (octant + DI_NODIR - mo.move_dir) % DI_NODIR
        if delta:
            ang = (ang - ANG45) & 0xFFFFFFFF if delta < 4 else (ang + ANG45) & 0xFFFFFFFF
        mo.angle = ang
    if target is None or not target.flags & MF_SHOOTABLE:
        if look_for_players(lv, mo, mobjs, True, tic):
            return NO_ACTION
        return enter_state(mo, mi("spawnstate", mo.kind))
    if mo.flags & MF_JUSTATTACKED:
        mo.flags &= ~MF_JUSTATTACKED
        new_chase_dir(lv, mo, target, rng, mobjs)
        return NO_ACTION
    melee = mi("meleestate", mo.kind)
    if melee and check_melee_range(lv, mo, target, tic):
        return enter_state(mo, melee)
    missile = mi("missilestate", mo.kind)
    if missile and mo.move_count == 0 and check_missile_range(lv, mo, target, rng, tic):
        mo.flags |= MF_JUSTATTACKED
        return enter_state(mo, missile)
    if mo.move_count == 0:
        new_chase_dir(lv, mo, target, rng, mobjs)
    else:
        mo.move_count -= 1
        if not p_move(lv, mo, mobjs):
            new_chase_dir(lv, mo, target, rng, mobjs)
    if ACTIVESOUND[mo.kind] if mo.kind < len(ACTIVESOUND) else 0:
        rng.next()
    return NO_ACTION


