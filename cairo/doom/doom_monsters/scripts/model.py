import importlib.util
import json
import random
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CRATE = HERE.parent
PHYSICS = CRATE.parent / "doom_physics" / "scripts"
THINGS = CRATE.parent / "doom_things" / "src" / "tables.cairo"

# Loaded under its own name: both files are called `model.py`, and a bare
# `import model` would find this one again.
_spec = importlib.util.spec_from_file_location("doom_physics_model", PHYSICS / "model.py")
phys = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(phys)

FRACUNIT = phys.FRACUNIT
BIAS = phys.BIAS
MAXSTEP = phys.MAXSTEP
NO_MOBJ = 0xFFFF

# -- p_enemy.c's own tables -------------------------------------------------

DI_EAST, DI_NORTHEAST, DI_NORTH, DI_NORTHWEST = 0, 1, 2, 3
DI_WEST, DI_SOUTHWEST, DI_SOUTH, DI_SOUTHEAST = 4, 5, 6, 7
DI_NODIR = 8
OPPOSITE = [DI_WEST, DI_SOUTHWEST, DI_SOUTH, DI_SOUTHEAST, DI_EAST, DI_NORTHEAST, DI_NORTH,
            DI_NORTHWEST, DI_NODIR]
DIAGS = [DI_NORTHWEST, DI_NORTHEAST, DI_SOUTHWEST, DI_SOUTHEAST]
XSPEED = [FRACUNIT, 47000, 0, -47000, -FRACUNIT, -47000, 0, 47000]
YSPEED = [0, 47000, FRACUNIT, 47000, 0, -47000, -FRACUNIT, -47000]

MELEERANGE = 64 * FRACUNIT
MISSILERANGE = 32 * 64 * FRACUNIT
SIGHT_TTL = 8
LOOK_CADENCE = 4
WINDOW = 8

MF_SOLID = 2
MF_SHOOTABLE = 4
MF_AMBUSH = 32
MF_JUSTATTACKED = 128
MF_JUSTHIT = 64
MF_COUNTKILL = 1 << 22

ANG90 = 0x40000000
ANG180 = 0x80000000
ANG270 = 0xC0000000
ANG45 = 0x20000000


def enc(raw: int) -> int:
    return raw + BIAS


