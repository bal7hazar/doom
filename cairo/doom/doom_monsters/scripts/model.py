def parse_tables(path: Path) -> dict:
    txt = path.read_text()
    out: dict = {}
    for m in re.finditer(r"pub const ([A-Z0-9_]+): \[[a-z0-9]+; (\d+)\] = \[(.*?)\];", txt, re.S):
        name, n, body = m.group(1), int(m.group(2)), m.group(3)
        vals = [int(v) for v in body.replace("\n", " ").split(",") if v.strip()]
        if len(vals) != n:
            raise SystemExit("table %s: %d values for a length of %d" % (name, len(vals), n))
        out[name] = vals
    for m in re.finditer(r"pub const ([A-Z0-9_]+): u32 = (\d+);", txt):
        out[m.group(1)] = int(m.group(2))
    return out


T = parse_tables(THINGS)
FOREVER = 0xFFFFFFFF
NO_ACTION = 0
A_LOOK = T["A_LOOK"]
A_CHASE = T["A_CHASE"]
A_FACETARGET = T["A_FACETARGET"]
KINDS = {
    "possessed": T["KIND_POSSESSED"],
    "shotguy": T["KIND_SHOTGUY"],
    "troop": T["KIND_TROOP"],
    "sergeant": T["KIND_SERGEANT"],
    "shadows": T["KIND_SHADOWS"],
}


def mi(col: str, kind: int) -> int:
    return T["MI_" + col.upper()][kind]


def radius_of(kind: int) -> int:
    return T["MI_RADIUS"][kind] - BIAS


def height_of(kind: int) -> int:
    return T["MI_HEIGHT"][kind] - BIAS


class Rng:
    """`prng::Prng` over `doom_things`' `rndtable`: read, then advance."""

    def __init__(self, index: int) -> None:
        self.index = index % 256

    def next(self) -> int:
        v = T["RNDTABLE"][self.index]
        self.index = 0 if self.index == 255 else self.index + 1
        return v

    def sub_random(self) -> int:
        return self.next() - self.next()


# --------------------------------------------------------------------------
# A mobj, as much of one as the AI reads
# --------------------------------------------------------------------------


class Mon:
    def __init__(self, lv, kind: int, x: int, y: int, flags_extra: int = 0) -> None:
        self.kind = kind
        self.x, self.y = x, y
        self.radius = radius_of(kind)
        self.height = height_of(kind)
        self.sector = lv.sector_at(x, y)
        self.floorz, self.ceilingz = lv.sectors[self.sector]
        self.z = self.floorz
        self.angle = 0
        self.flags = mi("flags", kind) | flags_extra
        self.health = mi("spawnhealth", kind)
        self.state = mi("spawnstate", kind)
        self.tics = T["STATE_TICS"][self.state]
        self.target = NO_MOBJ
        self.reaction_time = mi("reactiontime", kind)
        self.threshold = 0
        self.move_dir = 0
        self.move_count = 0
        self.sight_expires = 0
        self.sight_sector = 0
        self.sight_ok = False

    def as_sight(self):
        return (self.x, self.y, self.z, self.height)


def check_sight(lv, a: Mon, b: Mon) -> bool:
    if lv.reject(a.sector, b.sector):
        return False
    visible, _ = phys.check_sight_exact(lv, a.as_sight(), b.as_sight())
    return visible


def check_sight_cached(lv, a: Mon, b: Mon, tic: int) -> bool:
    if tic < a.sight_expires and b.sector == a.sight_sector:
        return a.sight_ok
    ok = check_sight(lv, a, b)
    a.sight_ok = ok
    a.sight_sector = b.sector
    a.sight_expires = tic + SIGHT_TTL
    return ok


def approx_distance(dx: int, dy: int) -> int:
    """`P_AproxDistance`: `dx + dy - (min >> 1)` on absolute values."""
    dx, dy = abs(dx), abs(dy)
    return dx + dy - ((dy if dy < dx else dx) >> 1)


def blocked_by_thing(mo: Mon, x: int, y: int, others: list[Mon]) -> bool:
    """`PIT_CheckThing`'s solid half, for a walker."""
    for th in others:
        if th is mo:
            continue
        if not th.flags & (MF_SOLID | MF_SHOOTABLE):
            continue
        blockdist = th.radius + mo.radius
        if abs(th.x - x) >= blockdist or abs(th.y - y) >= blockdist:
            continue
        if th.flags & MF_SOLID:
            return True
    return False


def try_move(lv, mo: Mon, x: int, y: int, others: list[Mon]) -> bool:
    """`P_TryMove` for a walker: the physics model plus `PIT_CheckThing`."""
    if blocked_by_thing(mo, x, y, others):
        return False
    pm = phys.Mobj(mo.x, mo.y, mo.z, mo.radius, mo.height, False)
    ok, floorz, ceilingz, _dropoffz, _blocker, _crossed = phys.try_move(lv, pm, x, y)
    if not ok:
        return False
    mo.x, mo.y = x, y
    mo.floorz, mo.ceilingz = floorz, ceilingz
    mo.sector = lv.sector_at(x, y)
    return True


# --------------------------------------------------------------------------
# P_Move / P_TryWalk / P_NewChaseDir
# --------------------------------------------------------------------------


def p_move(lv, mo: Mon, others: list[Mon]) -> bool:
    if mo.move_dir >= DI_NODIR:
        return False
    speed = mi("speed", mo.kind)
    tryx = mo.x + speed * XSPEED[mo.move_dir]
    tryy = mo.y + speed * YSPEED[mo.move_dir]
    if not try_move(lv, mo, tryx, tryy, others):
        return False
    mo.z = mo.floorz
    return True


def try_walk(lv, mo: Mon, rng: Rng, others: list[Mon]) -> bool:
    if not p_move(lv, mo, others):
        return False
    mo.move_count = rng.next() & 15
    return True


def new_chase_dir(lv, mo: Mon, target: Mon, rng: Rng, others: list[Mon]) -> None:
    olddir = mo.move_dir
    turnaround = OPPOSITE[olddir]
    deltax = target.x - mo.x
    deltay = target.y - mo.y
    if deltax > 10 * FRACUNIT:
        d1 = DI_EAST
    elif deltax < -10 * FRACUNIT:
        d1 = DI_WEST
    else:
        d1 = DI_NODIR
    if deltay < -10 * FRACUNIT:
        d2 = DI_SOUTH
    elif deltay > 10 * FRACUNIT:
        d2 = DI_NORTH
    else:
        d2 = DI_NODIR
    if d1 != DI_NODIR and d2 != DI_NODIR:
        mo.move_dir = DIAGS[((1 if deltay < 0 else 0) << 1) + (1 if deltax > 0 else 0)]
        if mo.move_dir != turnaround and try_walk(lv, mo, rng, others):
            return
    if rng.next() > 200 or abs(deltay) > abs(deltax):
        d1, d2 = d2, d1
    if d1 == turnaround:
        d1 = DI_NODIR
    if d2 == turnaround:
        d2 = DI_NODIR
    if d1 != DI_NODIR:
        mo.move_dir = d1
        if try_walk(lv, mo, rng, others):
            return
    if d2 != DI_NODIR:
        mo.move_dir = d2
        if try_walk(lv, mo, rng, others):
            return
    if olddir != DI_NODIR:
        mo.move_dir = olddir
        if try_walk(lv, mo, rng, others):
            return
    order = range(DI_EAST, DI_SOUTHEAST + 1) if rng.next() & 1 else range(DI_SOUTHEAST, DI_EAST - 1, -1)
    for tdir in order:
        if tdir == turnaround:
            continue
        mo.move_dir = tdir
        if try_walk(lv, mo, rng, others):
            return
    if turnaround != DI_NODIR:
        mo.move_dir = turnaround
        if try_walk(lv, mo, rng, others):
            return
    mo.move_dir = DI_NODIR


# --------------------------------------------------------------------------
# Range checks
# --------------------------------------------------------------------------


def check_melee_range(lv, mo: Mon, target: Mon, tic: int) -> bool:
    dist = approx_distance(target.x - mo.x, target.y - mo.y)
    if dist >= MELEERANGE - 20 * FRACUNIT + target.radius:
        return False
    return check_sight_cached(lv, mo, target, tic)


def check_missile_range(lv, mo: Mon, target: Mon, rng: Rng, tic: int) -> bool:
    if not check_sight_cached(lv, mo, target, tic):
        return False
    if mo.flags & MF_JUSTHIT:
        mo.flags &= ~MF_JUSTHIT
        return True
    if mo.reaction_time:
        return False
    dist = approx_distance(mo.x - target.x, mo.y - target.y) - 64 * FRACUNIT
    if not mi("meleestate", mo.kind):
        dist -= 128 * FRACUNIT
    dist >>= 16  # arithmetic: floors toward minus infinity, as C does
    if dist > 200:
        dist = 200
    return not rng.next() < dist


