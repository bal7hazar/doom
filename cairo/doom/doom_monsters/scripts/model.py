"""Reference model for `doom_monsters`, over `tools/wad`'s JSON of a map.

A transcription of linuxdoom-1.10's `p_enemy.c` -- `P_Move`, `P_TryWalk`,
`P_NewChaseDir`, `P_CheckMeleeRange`, `P_CheckMissileRange`,
`P_LookForPlayers`, `A_Look` and `A_Chase` -- and **not** of the Cairo code.
It borrows two things it must not re-derive:

* the geometry, from `doom_physics/scripts/model.py`: `try_move`
  (`P_CheckPosition` in exact integers over the real E1M1) and
  `check_sight_exact` (`P_CheckSight` in exact rationals). Those two models
  are themselves checked bit-exactly against the Cairo physics by that
  crate's own vectors, so a disagreement here is this crate's;
* the `info.c` numbers, read out of `doom_things/src/tables.cairo` -- data,
  generated from the C tables by that crate and verified against `info.c` by
  its tests.

Everything else (the direction tables, the probability rules, the RNG order,
the state walk) is written here from the C semantics.

`--write` emits `src/tests/vectors.cairo`; the Cairo tests replay every
vector. Coordinates are emitted in `fixed`'s offset encoding
(`enc = raw + 2^32`) so that every felt stays non-negative and below 2^72.

Usage:
    python3 model.py --json <e1m1.json> [--write] [--seed 1]
"""

