def gen_chasedirs(lv, rng: random.Random, n: int) -> list[int]:
    """`P_NewChaseDir` on the real E1M1: a zombieman at a subsector centroid
    with a target somewhere else, for every starting `movedir`."""
    out: list[int] = []
    kind = KINDS["possessed"]
    moved = 0
    while len(out) < n * 12:
        mx, my, _ = phys.inside_point(lv, rng)
        tx, ty, _ = phys.inside_point(lv, rng)
        if (mx, my) == (tx, ty):
            continue
        olddir = rng.randrange(0, 9)
        seed = rng.randrange(0, 256)
        mo = Mon(lv, kind, mx, my)
        mo.move_dir = olddir
        target = Mon(lv, T["KIND_PLAYER"], tx, ty)
        r = Rng(seed)
        new_chase_dir(lv, mo, target, r, [mo, target])
        moved += int((mo.x, mo.y) != (mx, my))
        out.extend(
            [enc(mx), enc(my), enc(tx), enc(ty), olddir, seed,
             mo.move_dir, enc(mo.x), enc(mo.y), mo.move_count, r.index,
             int((mo.x, mo.y) != (mx, my))]
        )
    print("chasedirs: %d cases, %d of which actually stepped" % (n, moved))
    return out


def gen_missile_ranges(rng: random.Random, n: int) -> list[int]:
    """`P_CheckMissileRange`'s probability rule, sight and `MF_JUSTHIT`
    already decided by the caller: distance, melee, reaction time, RNG."""
    out: list[int] = []
    for _ in range(n):
        dist = rng.randrange(0, 1200 * FRACUNIT)
        has_melee = rng.randrange(0, 2)
        reaction = rng.randrange(0, 2) * 8
        seed = rng.randrange(0, 256)
        d = dist - 64 * FRACUNIT
        if not has_melee:
            d -= 128 * FRACUNIT
        d >>= 16
        if d > 200:
            d = 200
        r = Rng(seed)
        if reaction:
            verdict = 0
        else:
            verdict = int(not r.next() < d)
        out.extend([enc(dist), has_melee, reaction, seed, verdict, r.index])
    print("missile ranges: %d cases" % n)
    return out


def gen_melees(lv, rng: random.Random, n: int) -> list[int]:
    """`P_CheckMeleeRange`: the distance rule and the sight test, on pairs
    close enough for the first to be interesting."""
    out: list[int] = []
    hits = 0
    kind = KINDS["sergeant"]
    while len(out) < n * 9:
        mx, my, _ = phys.inside_point(lv, rng)
        dx = rng.randrange(-90 * FRACUNIT, 90 * FRACUNIT)
        dy = rng.randrange(-90 * FRACUNIT, 90 * FRACUNIT)
        tx, ty = mx + dx, my + dy
        if lv.cell_of(tx, ty) is None:
            continue
        mo = Mon(lv, kind, mx, my)
        target = Mon(lv, T["KIND_PLAYER"], tx, ty)
        dist = approx_distance(tx - mx, ty - my)
        near = dist < MELEERANGE - 20 * FRACUNIT + target.radius
        if near:
            visible, margin = phys.check_sight_exact(lv, mo.as_sight(), target.as_sight())
            if lv.reject(mo.sector, target.sector):
                visible = False
            elif margin is not None and abs(margin) < FRACUNIT // 8:
                continue
            verdict = int(visible)
        else:
            verdict = 0
        hits += verdict
        out.extend([enc(mx), enc(my), enc(mo.z), enc(tx), enc(ty), enc(target.z),
                    target.radius // FRACUNIT, mo.sector, verdict])
    print("melees: %d cases, %d in range and visible" % (n, hits))
    return out


def gen_looks(lv, rng: random.Random, n: int) -> list[int]:
    """`A_Look` through `P_LookForPlayers`: sight, and the 180-degree blind
    arc outside melee range. Pairs whose angle falls within a degree of the
    arc's edge are dropped (the model's `atan2` is not `tantoangle`)."""
    out: list[int] = []
    stats = [0, 0]
    dropped = 0
    kind = KINDS["possessed"]
    while len(out) < n * 9:
        mx, my, _ = phys.inside_point(lv, rng)
        if rng.random() < 0.6:
            # Bias toward pairs close enough to be a plausible wake-up.
            px = mx + rng.randrange(-400 * FRACUNIT, 400 * FRACUNIT)
            py = my + rng.randrange(-400 * FRACUNIT, 400 * FRACUNIT)
            if lv.cell_of(px, py) is None:
                continue
        else:
            px, py, _ = phys.inside_point(lv, rng)
        if (mx, my) == (px, py):
            continue
        s1, s2 = lv.sector_at(mx, my), lv.sector_at(px, py)
        rejected = lv.reject(s1, s2)
        if rejected and rng.random() < 0.8:
            continue
        angle = rng.randrange(0, 8) * ANG45
        mo = Mon(lv, kind, mx, my)
        mo.angle = angle
        player = Mon(lv, T["KIND_PLAYER"], px, py)
        if rejected:
            visible = False
        else:
            visible, margin = phys.check_sight_exact(lv, mo.as_sight(), player.as_sight())
            if margin is not None and abs(margin) < FRACUNIT // 8:
                dropped += 1
                continue
        verdict = 0
        if visible:
            an = (phys_point_to_angle(mx, my, px, py) - angle) & 0xFFFFFFFF
            edge = min(abs(an - ANG90), abs(an - ANG270))
            if edge < (1 << 32) // 360:
                dropped += 1
                continue
            if ANG90 < an < ANG270 and approx_distance(px - mx, py - my) > MELEERANGE:
                verdict = 0
            else:
                verdict = 1
        stats[verdict] += 1
        out.extend([enc(mx), enc(my), enc(mo.z), angle, enc(px), enc(py), enc(player.z),
                    int(visible), verdict])
    print("looks: %d cases (%d wake, %d do not), %d dropped for a thin margin"
          % (n, stats[1], stats[0], dropped))
    return out


CHASE_TICS = 300
CHASE_EVERY = 10


def gen_chase(lv, rng: random.Random) -> tuple[list[int], list[int]]:
    """A zombieman already awake, chasing a target it never gets to see.

    The point is to exercise `A_Chase`, `P_Move` and `P_NewChaseDir` for
    hundreds of tics against the real geometry without dragging the attacks
    (and their hitscans) into the model: as long as the sight test stays
    false, `A_Chase` can neither melee nor fire, so the trace is pure
    movement. The generator searches candidate pairs until it finds one that
    stays out of sight for the whole run, and emits the setup with the
    trace."""
    kind = KINDS["possessed"]
    for _ in range(4000):
        mx, my, _ = phys.inside_point(lv, rng)
        tx, ty, _ = phys.inside_point(lv, rng)
        if not lv.reject(lv.sector_at(mx, my), lv.sector_at(tx, ty)):
            continue
        if approx_distance(tx - mx, ty - my) < 400 * FRACUNIT:
            continue
        mo = Mon(lv, kind, mx, my)
        target = Mon(lv, T["KIND_PLAYER"], tx, ty)
        mo.target = 1
        mo.reaction_time = 0
        enter_state(mo, mi("seestate", kind))
        r = Rng(1)
        mobjs = [mo, target]
        trace: list[int] = []
        ok = True
        for tic in range(CHASE_TICS):
            if check_sight(lv, mo, target):
                ok = False
                break
            # `P_MobjThinker`: no momentum on a walker, so only the state
            # machine runs before the action.
            if mo.tics != FOREVER:
                if mo.tics > 1:
                    mo.tics -= 1
                    action = NO_ACTION
                else:
                    nxt = T["STATE_NEXT"][mo.state]
                    mo.state = nxt
                    mo.tics = T["STATE_TICS"][nxt]
                    action = T["STATE_ACTION"][nxt]
                if action == A_CHASE:
                    a_chase(lv, mo, mobjs, r, tic)
            if tic % CHASE_EVERY == CHASE_EVERY - 1:
                trace.extend([enc(mo.x), enc(mo.y), mo.move_dir, mo.move_count,
                              mo.state, mo.tics, r.index])
        if not ok:
            continue
        if approx_distance(mo.x - mx, mo.y - my) < 150 * FRACUNIT:
            continue  # the monster never got anywhere: not a useful trace
        setup = [enc(mx), enc(my), enc(tx), enc(ty)]
        print("chase: %d tics from (%.0f, %.0f) toward (%.0f, %.0f), ends at (%.0f, %.0f)"
              % (CHASE_TICS, mx / FRACUNIT, my / FRACUNIT, tx / FRACUNIT, ty / FRACUNIT,
                 (trace[-7] - BIAS) / FRACUNIT, (trace[-6] - BIAS) / FRACUNIT))
        return setup, trace
    raise SystemExit("no chase pair stayed out of sight for %d tics" % CHASE_TICS)


def gen_chains() -> list[int]:
    """The state walk of each kind, straight out of the generated tables:
    spawn -> see -> chase loop -> attack -> pain -> death, as the sequence of
    (state, tics, action) triples a `P_SetMobjState` chain visits."""
    out: list[int] = []
    for name in ("possessed", "shotguy", "troop", "sergeant", "shadows"):
        k = KINDS[name]
        for col in ("spawnstate", "seestate", "meleestate", "missilestate",
                    "painstate", "deathstate", "xdeathstate"):
            s = mi(col, k)
            out.extend([k, s, T["STATE_TICS"][s], T["STATE_ACTION"][s], T["STATE_NEXT"][s]])
    print("chains: %d rows" % (len(out) // 5))
    return out


